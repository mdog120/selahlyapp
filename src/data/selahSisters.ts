export function getDailySelahSister(): SelahSister {
    // Determine the current day of the year (0-365)
    // This allows the sister to rotate daily
    const now = new Date();
    const start = new Date(now.getFullYear(), 0, 0);
    const diff = (now.getTime() - start.getTime()) + ((start.getTimezoneOffset() - now.getTimezoneOffset()) * 60 * 1000);
    const oneDay = 1000 * 60 * 60 * 24;
    const dayOfYear = Math.floor(diff / oneDay);

    // Select a sister based on the day index
    return selahSisters[dayOfYear % selahSisters.length];
}
